package bench

import (
	"fmt"
	"sort"
	"strings"
	"time"
)

// Baseline is the profile every other row is compared against.
const Baseline = "baseline-j21"

// Render produces BENCHMARKS.md. Committed output, so a regression across a JDK
// or pack bump shows up in a diff rather than in someone's memory.
func Render(results []Result, host string, when time.Time) string {
	var b strings.Builder
	b.WriteString("# Benchmarks \U0001f496\n\n")
	b.WriteString("Generated by `wly bench`, so do not edit it by hand.\n\n")
	fmt.Fprintf(&b, "- measured by: %s\n", hostLine(results, host))
	fmt.Fprintf(&b, "- run: %s\n", when.UTC().Format(time.RFC3339))
	fmt.Fprintf(&b, "- medians of %s\n", repeatSummary(results))
	fmt.Fprintf(&b, "- anything under %.0f%% is noise on a shared VM and is shown as `~`\n\n",
		NoiseFloor*100)
	writeHardware(&b, results)
	b.WriteString("\n")

	for _, w := range AllWorkloads {
		rows := filter(results, w)
		if len(rows) == 0 {
			continue
		}
		sp := SpecFor(w)
		fmt.Fprintf(&b, "## %s\n\n", workloadTitle(w))
		// Which number this table is read by, stated where the numbers are. The
		// worldgen workloads are a throughput question and the tick workloads a
		// latency one, so `vs base` does not mean the same thing in both, and a
		// reader who assumes it does will read a win as a loss.
		dir := "higher is better"
		if sp.Metric.Lower {
			dir = "lower is better"
		}
		fmt.Fprintf(&b, "Read by **%s**, %s; `vs base` compares it.\n\n", sp.Metric.Label, dir)
		if w == WorkloadMachines {
			b.WriteString("Machines are powered but not fed: this is block entity ticking " +
				"and energy network cost, not production throughput.\n\n")
		}
		if n := modsOf(rows); n > 0 {
			// The caveat is about the pack growing, so it belongs only on the
			// pack workload. The control's count is Fabric API's nested jars
			// plus the pregenerator and does not move on its own.
			if sp.Pack {
				fmt.Fprintf(&b, "%d mods loaded. Rows are only comparable to other runs "+
					"against a similar pack, this one grows.\n\n", n)
			} else {
				fmt.Fprintf(&b, "%d mods loaded (Fabric API and the pregenerator).\n\n", n)
			}
		}
		// p95 alongside p99: p99 is the tail everyone quotes, but a collector
		// whose p95 is already high is stalling routinely rather than rarely,
		// and that is a different problem with a different fix.
		b.WriteString("| profile | heap | chunks/s | vs base | MSPT p95 | TPS | peak RSS | peak CPU | startup | GC p95 | GC p99 |\n")
		b.WriteString("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n")
		base := baselineOf(rows, sp.Metric)
		for _, r := range rows {
			if r.Failed() {
				// Every column would otherwise be a zero, and the delta a
				// confident -100%. Say what happened instead.
				fmt.Fprintf(&b, "| `%s` | %s | FAILED | - | - | - | - | - | - | - | - |\n",
					r.Profile, r.Heap)
				continue
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %.1fms | %.1f | %s | %.0f%% | %.1fs | %.1fms | %.1fms |\n",
				r.Profile, r.Heap, throughput(sp, r), delta(base, sp.Metric.Of(r), sp.Metric),
				r.MSPTP95(), r.TPS(),
				humanBytes(r.PeakRSS()), r.PeakCPU(), r.Startup(),
				r.GCPause(95), r.GCPause(99))
		}
		b.WriteString("\n")
		if n := watchdogNote(rows); n != "" {
			b.WriteString(n + "\n")
		}
		if d := droppedNote(rows); d != "" {
			b.WriteString(d + "\n")
		}
	}
	return b.String()
}

func workloadTitle(w Workload) string {
	if t := SpecFor(w).Title; t != "" {
		return t
	}
	// A shard file from an older build can name a workload this one has never
	// heard of. Printing its name beats dropping the rows.
	return string(w)
}

// throughput renders the chunks/s cell. A tick workload generates no chunks, and
// a 0.0 there would read as a measurement rather than as an absence.
func throughput(sp Spec, r Result) string {
	if !sp.Worldgen() {
		return "-"
	}
	return fmt.Sprintf("%.1f", r.ChunksPerSec())
}

// hostLine names the machines that did the measuring.
//
// The rendering machine's hostname is the fallback, not the answer: a sharded
// sweep is measured on several boxes and merged on an ubuntu-latest runner, and
// the first real sweep duly published `host: runnervm76f27`, which is a machine
// that never ran a benchmark.
func hostLine(rs []Result, renderedOn string) string {
	if hosts := Hosts(rs); len(hosts) > 0 {
		return strings.Join(hosts, ", ")
	}
	if renderedOn == "" {
		// Saying so beats naming the machine that happened to render the file.
		// Shards written before Result.Host existed land here.
		return "unrecorded"
	}
	return renderedOn
}

// Failed reports whether every run of this result failed.
//
// benchCmd skips a failed run, so a profile that never completed one has no
// runs at all and every median comes out zero. Rendered as numbers that is a
// catastrophic score rather than an absence: the first real sweep published
// `j25-shenandoah-gen` at 0.0 chunks/s and -100.0%, which reads as a measurement
// and is not one.
func (res Result) Failed() bool { return len(res.Runs) == 0 }

// watchdogNote names the profiles whose server hung hard enough for its own
// watchdog to kill it. That is not a bad score, it is a failure, and it is the
// most interesting thing a tick workload can find.
func watchdogNote(rs []Result) string {
	var names []string
	for _, r := range rs {
		for _, run := range r.Runs {
			if run.Watchdog {
				names = append(names, r.Profile)
				break
			}
		}
	}
	if len(names) == 0 {
		return ""
	}
	sort.Strings(names)
	return "**The watchdog killed the server on: `" + strings.Join(names, "`, `") +
		"`.** A hung tick is a failed profile, not a slow one.\n"
}

// modsOf reports the mod count these rows were measured against, or 0 if no run
// logged one. Every row in a workload runs the same pack, so the first is enough.
func modsOf(rows []Result) int {
	for _, r := range rows {
		if n := r.Mods(); n > 0 {
			return n
		}
	}
	return 0
}

func filter(rs []Result, w Workload) []Result {
	var out []Result
	for _, r := range rs {
		if r.Workload == w {
			out = append(out, r)
		}
	}
	// Baseline first, then alphabetical: the row everything is measured against
	// belongs at the top.
	sort.SliceStable(out, func(i, j int) bool {
		if (out[i].Profile == Baseline) != (out[j].Profile == Baseline) {
			return out[i].Profile == Baseline
		}
		return out[i].Profile < out[j].Profile
	})
	return out
}

func baselineOf(rs []Result, m Metric) float64 {
	for _, r := range rs {
		if r.Profile == Baseline {
			return m.Of(r)
		}
	}
	if len(rs) > 0 {
		return m.Of(rs[0])
	}
	return 0
}

// delta signs a comparison the way the metric reads. Throughput going up is a
// win and tick duration going up is a loss, so the sign is flipped for a
// lower-is-better metric: every row in the table then means "better" when it is
// positive, whatever the column is measuring.
func delta(base, v float64, m Metric) string {
	if base == 0 {
		return "-"
	}
	if !Significant(base, v) {
		return "~"
	}
	change := RelChange(base, v)
	if m.Lower {
		change = -change
	}
	return fmt.Sprintf("%+.1f%%", change*100)
}

func humanBytes(b float64) string {
	switch {
	case b >= 1<<30:
		return fmt.Sprintf("%.2f GiB", b/(1<<30))
	case b >= 1<<20:
		return fmt.Sprintf("%.0f MiB", b/(1<<20))
	default:
		return fmt.Sprintf("%.0f B", b)
	}
}

func repeatSummary(rs []Result) string {
	n := 0
	for _, r := range rs {
		if len(r.Runs) > n {
			n = len(r.Runs)
		}
	}
	if n == 1 {
		return "1 run per profile"
	}
	return fmt.Sprintf("%d runs per profile", n)
}

// droppedNote surfaces flags the JVM refused. Silently dropping them would make
// two profiles look identical when one of them never applied.
func droppedNote(rs []Result) string {
	seen := map[string][]string{}
	for _, r := range rs {
		if len(r.Dropped) > 0 {
			seen[r.Profile] = r.Dropped
		}
	}
	if len(seen) == 0 {
		return ""
	}
	names := make([]string, 0, len(seen))
	for k := range seen {
		names = append(names, k)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("Flags the JVM refused during preflight:\n\n")
	for _, n := range names {
		fmt.Fprintf(&b, "- `%s`: %s\n", n, strings.Join(seen[n], ", "))
	}
	return b.String()
}

// writeHardware names the machine, and refuses to be quiet when a table mixes
// more than one.
//
// A sharded sweep runs on several boxes, and they are not automatically the
// same: two provisioned on the same day came up AmpereOne with four threads
// instead of Neoverse-N1 with two. Numbers from both in one table look like a
// flag winning when they are really two different machines, so the mixture is
// stated where the numbers are, not left in a commit message.
func writeHardware(b *strings.Builder, results []Result) {
	hw := HardwareSpread(results)
	switch len(hw) {
	case 0:
	case 1:
		fmt.Fprintf(b, "- measured on: %s\n", hw[0])
	default:
		b.WriteString("- **measured on more than one machine, so these rows are not directly comparable:**\n")
		for _, h := range hw {
			fmt.Fprintf(b, "  - %s\n", h)
		}
	}
}
