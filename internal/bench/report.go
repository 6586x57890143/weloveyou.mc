package bench

import (
	"fmt"
	"sort"
	"strings"
	"time"
)

// Baseline is the profile every other row is compared against.
const Baseline = "baseline-j21"

// Render produces BENCHMARKS.md. Committed output, so a regression across a JDK
// or pack bump shows up in a diff rather than in someone's memory.
func Render(results []Result, host string, when time.Time) string {
	var b strings.Builder
	b.WriteString("# Benchmarks\n\n")
	b.WriteString("Generated by `wly bench`. Do not edit by hand.\n\n")
	fmt.Fprintf(&b, "- host: %s\n", host)
	fmt.Fprintf(&b, "- run: %s\n", when.UTC().Format(time.RFC3339))
	fmt.Fprintf(&b, "- medians of %s\n", repeatSummary(results))
	fmt.Fprintf(&b, "- anything under %.0f%% is noise on a shared VM and is shown as `~`\n\n",
		NoiseFloor*100)

	for _, w := range []Workload{WorkloadVanilla, WorkloadPack} {
		rows := filter(results, w)
		if len(rows) == 0 {
			continue
		}
		fmt.Fprintf(&b, "## %s\n\n", workloadTitle(w))
		if n := modsOf(rows); n > 0 {
			fmt.Fprintf(&b, "%d mods loaded. Rows are only comparable to other runs "+
				"against a similar pack — this one grows.\n\n", n)
		}
		b.WriteString("| profile | chunks/s | vs base | peak RSS | startup | GC p99 |\n")
		b.WriteString("|---|---:|---:|---:|---:|---:|\n")
		base := baselineOf(rows)
		for _, r := range rows {
			fmt.Fprintf(&b, "| `%s` | %.1f | %s | %s | %.1fs | %.1fms |\n",
				r.Profile, r.ChunksPerSec(), delta(base, r.ChunksPerSec()),
				humanBytes(r.PeakRSS()), r.Startup(), r.GCPause(99))
		}
		b.WriteString("\n")
		if d := droppedNote(rows); d != "" {
			b.WriteString(d + "\n")
		}
	}
	return b.String()
}

func workloadTitle(w Workload) string {
	if w == WorkloadVanilla {
		return "Workload A - vanilla worldgen (control)"
	}
	return "Workload B - the pack we actually ship"
}

// modsOf reports the mod count these rows were measured against, or 0 if no run
// logged one. Every row in a workload runs the same pack, so the first is enough.
func modsOf(rows []Result) int {
	for _, r := range rows {
		if n := r.Mods(); n > 0 {
			return n
		}
	}
	return 0
}

func filter(rs []Result, w Workload) []Result {
	var out []Result
	for _, r := range rs {
		if r.Workload == w {
			out = append(out, r)
		}
	}
	// Baseline first, then alphabetical: the row everything is measured against
	// belongs at the top.
	sort.SliceStable(out, func(i, j int) bool {
		if (out[i].Profile == Baseline) != (out[j].Profile == Baseline) {
			return out[i].Profile == Baseline
		}
		return out[i].Profile < out[j].Profile
	})
	return out
}

func baselineOf(rs []Result) float64 {
	for _, r := range rs {
		if r.Profile == Baseline {
			return r.ChunksPerSec()
		}
	}
	if len(rs) > 0 {
		return rs[0].ChunksPerSec()
	}
	return 0
}

func delta(base, v float64) string {
	if base == 0 {
		return "-"
	}
	if !Significant(base, v) {
		return "~"
	}
	return fmt.Sprintf("%+.1f%%", RelChange(base, v)*100)
}

func humanBytes(b float64) string {
	switch {
	case b >= 1<<30:
		return fmt.Sprintf("%.2f GiB", b/(1<<30))
	case b >= 1<<20:
		return fmt.Sprintf("%.0f MiB", b/(1<<20))
	default:
		return fmt.Sprintf("%.0f B", b)
	}
}

func repeatSummary(rs []Result) string {
	n := 0
	for _, r := range rs {
		if len(r.Runs) > n {
			n = len(r.Runs)
		}
	}
	if n == 1 {
		return "1 run per profile"
	}
	return fmt.Sprintf("%d runs per profile", n)
}

// droppedNote surfaces flags the JVM refused. Silently dropping them would make
// two profiles look identical when one of them never applied.
func droppedNote(rs []Result) string {
	seen := map[string][]string{}
	for _, r := range rs {
		if len(r.Dropped) > 0 {
			seen[r.Profile] = r.Dropped
		}
	}
	if len(seen) == 0 {
		return ""
	}
	names := make([]string, 0, len(seen))
	for k := range seen {
		names = append(names, k)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("Flags the JVM refused during preflight:\n\n")
	for _, n := range names {
		fmt.Fprintf(&b, "- `%s`: %s\n", n, strings.Join(seen[n], ", "))
	}
	return b.String()
}
